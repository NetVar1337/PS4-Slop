#!/bin/sh
# setup-toolchain.sh — install the PS4 payload build toolchain for these repos:
#   1. OpenOrbis PS4 SDK (headers, NID link stubs, link.x) — pinned archive + SHA-256
#   2. Vanilla LLVM clang/ld.lld (must be on PATH; see instructions below)
#   3. ps4-payload-sdk-style shim: ~/.local/ps4-payload-sdk/bin/orbis-clang
#      so Injector-PS4/Fortnite-PS4 Makefiles work unchanged.
#
# Idempotent. Never touches the console. Run from anywhere.
set -eu

WIN_VERSION=v0.5.3
WIN_URL="https://github.com/OpenOrbis/OpenOrbis-PS4-Toolchain/releases/download/${WIN_VERSION}/toolchain-llvm-18.2.zip"
WIN_SHA256=5006bb8629a40093b712fac971456fa4d5ad3fafaadb16d11c10b8a93b8b496f
LINUX_VERSION=v0.5.4
LINUX_URL="https://github.com/OpenOrbis/OpenOrbis-PS4-Toolchain/releases/download/${LINUX_VERSION}/toolchain-llvm-18.tar.gz"
LINUX_SHA256=3c7cd5bb593ca74fa1c13fd59f3938dc0fc07985167f7275063019e63abe4526

DATA_HOME="${XDG_DATA_HOME:-$HOME/.local}"
OO_DIR="$DATA_HOME/openorbis-ps4-toolchain"
SHIM_DIR="$DATA_HOME/ps4-payload-sdk/bin"
ARCHIVE_DIR="$DATA_HOME/downloads"
FORCE=0
[ "${1:-}" = "--force" ] && FORCE=1

log() { printf '%s\n' "[setup-toolchain] $*"; }
die() { printf '%s\n' "[setup-toolchain] ERROR: $*" >&2; exit 1; }

# --- 1. clang / lld -----------------------------------------------------------
CLANG="$(command -v clang || true)"
LLD="$(command -v ld.lld || true)"
CLANGXX="$(command -v clang++ || true)"
if [ -z "$CLANG" ] || [ -z "$LLD" ] || [ -z "$CLANGXX" ]; then
    cat >&2 <<'EOF'
[setup-toolchain] clang / clang++ / ld.lld not found on PATH.
  Debian/Ubuntu: sudo apt install clang lld
  Arch:          sudo pacman -S clang lld
  macOS:         brew install llvm   (then add "$(brew --prefix llvm)/bin" to PATH)
  Windows:       winget install LLVM.LLVM  (use setup-toolchain.ps1 instead)
Re-run after installing.
EOF
    exit 1
fi
"$CLANG" --version | head -1

# --- 2. OpenOrbis SDK ---------------------------------------------------------
mkdir -p "$ARCHIVE_DIR"
sha256() {
    if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | cut -d' ' -f1
    else shasum -a 256 "$1" | cut -d' ' -f1; fi
}

case "$(uname -s)" in
    Darwin*) die "macOS is not pinned by this script yet; use the Linux archive and adjust manually" ;;
    MINGW*|MSYS*|CYGWIN*) ARCHIVE="$ARCHIVE_DIR/openorbis-win.zip"; URL="$WIN_URL"; WANT="$WIN_SHA256" ;;
    *) ARCHIVE="$ARCHIVE_DIR/openorbis-linux.tar.gz"; URL="$LINUX_URL"; WANT="$LINUX_SHA256" ;;
esac

if [ "$FORCE" = 1 ] || [ ! -f "$ARCHIVE" ] || [ "$(sha256 "$ARCHIVE")" != "$WANT" ]; then
    log "downloading $URL"
    curl -fL --retry 2 -o "$ARCHIVE" "$URL"
fi
[ "$(sha256 "$ARCHIVE")" = "$WANT" ] || die "SHA-256 mismatch for $ARCHIVE (expected $WANT)"

if [ "$FORCE" = 1 ] || [ ! -f "$OO_DIR/link.x" ]; then
    log "extracting to $OO_DIR"
    rm -rf "$OO_DIR" "$ARCHIVE_DIR/oo-extract"
    mkdir -p "$ARCHIVE_DIR/oo-extract"
    case "$ARCHIVE" in
        *.zip) unzip -q -o "$ARCHIVE" -d "$ARCHIVE_DIR/oo-extract" ;;
        *.tar.gz) tar -xzf "$ARCHIVE" -C "$ARCHIVE_DIR/oo-extract" ;;
    esac
    # The v0.5.3 Windows zip wraps the real SDK in a nested tar.gz.
    if [ ! -d "$ARCHIVE_DIR/oo-extract/OpenOrbis/PS4Toolchain" ]; then
        nested="$(find "$ARCHIVE_DIR/oo-extract" -name '*.tar.gz' | head -1)"
        [ -n "$nested" ] && tar -xzf "$nested" -C "$ARCHIVE_DIR/oo-extract"
    fi
    mv "$ARCHIVE_DIR/oo-extract/OpenOrbis/PS4Toolchain" "$OO_DIR"
    rm -rf "$ARCHIVE_DIR/oo-extract"
fi
[ -f "$OO_DIR/link.x" ] && [ -f "$OO_DIR/lib/crt1.o" ] || die "OpenOrbis layout unexpected at $OO_DIR"

# --- 3. ps4-payload-sdk-style shim -------------------------------------------
mkdir -p "$SHIM_DIR"
cat > "$SHIM_DIR/orbis-clang" <<EOF
#!/bin/sh
# Generated by PS4-DebugMCPs/scripts/setup-toolchain.sh — vanilla clang + OpenOrbis SDK.
OO="$OO_DIR"
CLANG="$CLANG"
link=1
for a in "\$@"; do case "\$a" in -c|-S|-E) link=0 ;; esac; done
if [ "\$link" = 1 ]; then
    exec "\$CLANG" --target=x86_64-pc-freebsd12-elf -fPIC -funwind-tables \\
        -isysroot "\$OO" -isystem "\$OO/include" -isystem "\$OO/include/c++/v1" \\
        -nostdlib -fuse-ld=lld -Wl,-m,elf_x86_64,-pie,--script,"\$OO/link.x" -Wl,--eh-frame-hdr \\
        -L"\$OO/lib" -lkernel -lc "\$OO/lib/crt1.o" "\$@"
else
    exec "\$CLANG" --target=x86_64-pc-freebsd12-elf -fPIC -funwind-tables \\
        -isysroot "\$OO" -isystem "\$OO/include" -isystem "\$OO/include/c++/v1" "\$@"
fi
EOF
chmod +x "$SHIM_DIR/orbis-clang"
cp "$SHIM_DIR/orbis-clang" "$SHIM_DIR/orbis-clang++"

log "done."
printf '\nAdd to your shell profile:\n'
printf '  export OO_PS4_TOOLCHAIN=%s\n' "$OO_DIR"
printf '  export PS4_PAYLOAD_SDK=%s\n' "$DATA_HOME/ps4-payload-sdk"
printf '\nFortnite-PS4:  make (OO_PS4_TOOLCHAIN=%s)\n' "$OO_DIR"
printf 'Injector-PS4:  make elf PS4_PAYLOAD_SDK=%s\n' "$DATA_HOME/ps4-payload-sdk"
printf 'Workbench SDK detection: ps4-workbench call sdk_status\n'

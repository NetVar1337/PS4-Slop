# setup-toolchain.ps1 — Windows variant of setup-toolchain.sh.
# Installs the OpenOrbis PS4 SDK (pinned zip + SHA-256) and writes a
# ps4-payload-sdk-style shim (orbis-clang.cmd) under ~/.local/ps4-payload-sdk.
# Requires vanilla LLVM clang/lld (winget install LLVM.LLVM). Idempotent.
[CmdletBinding()]
param(
    [switch]$Force,
    [string]$LlvmBin = "C:\Program Files\LLVM\bin"
)
$ErrorActionPreference = 'Stop'

$Version = 'v0.5.3'
$Url = "https://github.com/OpenOrbis/OpenOrbis-PS4-Toolchain/releases/download/$Version/toolchain-llvm-18.2.zip"
$Want = '5006bb8629a40093b712fac971456fa4d5ad3fafaadb16d11c10b8a93b8b496f'

$Data = Join-Path $HOME '.local'
$Oo = Join-Path $Data 'openorbis-ps4-toolchain'
$Shim = Join-Path $Data 'ps4-payload-sdk\bin'
$Downloads = Join-Path $Data 'downloads'
$Archive = Join-Path $Downloads 'openorbis-win.zip'

function Log($m) { Write-Host "[setup-toolchain] $m" }

foreach ($tool in @('clang.exe', 'clang++.exe', 'ld.lld.exe')) {
    if (-not (Get-Command (Join-Path $LlvmBin $tool) -ErrorAction SilentlyContinue) -and -not (Get-Command $tool -ErrorAction SilentlyContinue)) {
        throw "$tool not found. Install with: winget install LLVM.LLVM (or set -LlvmBin)"
    }
}
$Clang = if (Get-Command (Join-Path $LlvmBin 'clang.exe') -ErrorAction SilentlyContinue) { Join-Path $LlvmBin 'clang.exe' } else { (Get-Command 'clang.exe').Source }
& $Clang --version | Select-Object -First 1

New-Item -ItemType Directory -Force -Path $Downloads, $Shim | Out-Null
if ($Force -or -not (Test-Path $Archive) -or (Get-FileHash $Archive -Algorithm SHA256).Hash.ToLower() -ne $Want) {
    Log "downloading $Url"
    Invoke-WebRequest -Uri $Url -OutFile $Archive
}
$actual = (Get-FileHash $Archive -Algorithm SHA256).Hash.ToLower()
if ($actual -ne $Want) { throw "SHA-256 mismatch for $Archive (expected $Want)" }

if ($Force -or -not (Test-Path (Join-Path $Oo 'link.x'))) {
    Log "extracting to $Oo"
    $tmp = Join-Path $Downloads 'oo-extract'
    Remove-Item -Recurse -Force -ErrorAction SilentlyContinue $Oo, $tmp
    Expand-Archive -Path $Archive -DestinationPath $tmp -Force
    # The v0.5.3 Windows zip wraps the real SDK in a nested tar.gz.
    if (-not (Test-Path (Join-Path $tmp 'OpenOrbis\PS4Toolchain'))) {
        $nested = Get-ChildItem -Recurse -Filter '*.tar.gz' $tmp | Select-Object -First 1
        if ($nested) { tar -xzf $nested.FullName -C $tmp }
    }
    Move-Item (Join-Path $tmp 'OpenOrbis\PS4Toolchain') $Oo
    Remove-Item -Recurse -Force $tmp
}
if (-not (Test-Path (Join-Path $Oo 'lib\crt1.o'))) { throw "OpenOrbis layout unexpected at $Oo" }

$shimBody = @"
@echo off
rem Generated by PS4-MCP/scripts/setup-toolchain.ps1 — vanilla clang + OpenOrbis SDK.
setlocal
set "LINK=1"
for %%A in (%*) do (if "%%A"=="-c" set "LINK=0")
if "%LINK%"=="1" (
    "$Clang" --target=x86_64-pc-freebsd12-elf -fPIC -funwind-tables -isysroot "$Oo" -isystem "$Oo\include" -isystem "$Oo\include\c++\v1" -nostdlib -fuse-ld=lld -Wl,-m,elf_x86_64,-pie,--script,"$Oo\link.x" -Wl,--eh-frame-hdr -L"$Oo\lib" -lkernel -lc "$Oo\lib\crt1.o" %*
) else (
    "$Clang" --target=x86_64-pc-freebsd12-elf -fPIC -funwind-tables -isysroot "$Oo" -isystem "$Oo\include" -isystem "$Oo\include\c++\v1" %*
)
"@
Set-Content -Path (Join-Path $Shim 'orbis-clang.cmd') -Value $shimBody -Encoding ascii
Copy-Item (Join-Path $Shim 'orbis-clang.cmd') (Join-Path $Shim 'orbis-clang++.cmd') -Force

Log 'done.'
Write-Host ''
Write-Host 'Set for new shells:'
Write-Host "  setx OO_PS4_TOOLCHAIN `"$Oo`""
Write-Host "  setx PS4_PAYLOAD_SDK `"$(Join-Path $Data 'ps4-payload-sdk')`""
Write-Host 'Fortnite-PS4:  make (with make on PATH)'
Write-Host "Injector-PS4:  make elf PS4_PAYLOAD_SDK=$(Join-Path $Data 'ps4-payload-sdk')"
